export const main = `// This file is part of www.nand2tetris.org
// and the book "The Elements of Computing Systems"
// by Nisan and Schocken, MIT Press.
// File name: FibonacciElement/Main.vm

// Contains one function: Main.fibonacci. This function 
// Computes the nth Fibonacci number recursively, where n is
// supplied in argument[0]. The Sys.init function (in Sys.vm)
// calls Main.fibonacci with the desired input value (n).
function Main.fibonacci 0
	push argument 0
	push constant 2
	lt
	if-goto N_LT_2
	goto N_GE_2
label N_LT_2               // If n < 2, return n.
	push argument 0
	return
label N_GE_2               // Otherwise, return fib(n - 2) + fib(n - 1).
	push argument 0
	push constant 2
	sub
	call Main.fibonacci 1  // Compute fib(n - 2).
	push argument 0
	push constant 1
	sub
	call Main.fibonacci 1  // Compute fib(n - 1).
	add                    // Add the two results.
	return
`;

export const sys = `// This file is part of www.nand2tetris.org
// and the book "The Elements of Computing Systems"
// by Nisan and Schocken, MIT Press.
// File name: FibonacciElement/Sys.vm

// Containts one function: Sys.init.

// Pushes a constant n onto the stack, and calls the Main.fibonacii
// function, which computes the n'th element of the Fibonacci series.
// Note that by convention, the Sys.init function is called "automatically" 
// by the bootstrap code generated by the VM translator.
function Sys.init 0
    // Computes fibonacci(4)
	push constant 4
	// Calls the function, informing that one argument was pushed onto the stack
	call Main.fibonacci 1
label END  
	goto END  // loops infinitely`;

